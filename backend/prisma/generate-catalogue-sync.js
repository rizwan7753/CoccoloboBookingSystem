/**
 * Regenerates prisma/sync-catalogue-to-live.sql from whatever is in the local
 * database right now, so the hosted site can be brought in line with local:
 *
 *   node prisma/generate-catalogue-sync.js
 *
 * Covers the bookable catalogue — excursions (plus their departure times) and
 * rental items (plus their spots and time slots). It deliberately leaves
 * bookings, orders, locations and admin users alone.
 */
const fs = require("fs");
const path = require("path");
const { PrismaClient } = require("@prisma/client");

const prisma = new PrismaClient();

/** A marker for "emit this column as a raw SQL expression, not a literal". */
const rawExpr = (sql) => ({ __raw: sql });

function q(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "object" && v !== null && v.__raw) return v.__raw;
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "1" : "0";
  if (v instanceof Date) return `'${v.toISOString().slice(0, 19).replace("T", " ")}'`;
  // Prisma hands decimals back as objects, and images[] as JSON text already.
  if (typeof v === "object") return q(String(v));
  return "'" + String(v).replace(/\\/g, "\\\\").replace(/'/g, "''") + "'";
}

/**
 * INSERT ... ON DUPLICATE KEY UPDATE keyed on the table's own unique index, so
 * a row that already exists on the host is updated in place and keeps its id —
 * and therefore keeps any bookings pointing at it.
 */
function upsert(table, cols, row, keyCols) {
  const sets = cols.filter((c) => c !== "id" && !keyCols.includes(c)).map((c) => `${c} = VALUES(${c})`);
  return (
    `INSERT INTO ${table} (${cols.join(", ")})\n` +
    `VALUES (${cols.map((c) => q(row[c])).join(", ")})\n` +
    `ON DUPLICATE KEY UPDATE ${sets.join(", ")};\n`
  );
}

/** Same, but the parent id is looked up by slug because it differs on the host. */
function upsertChild(table, cols, row, parentCol, parentTable, parentSlug, keyCols) {
  const select = cols.map((c) => (c === parentCol ? "p.id" : q(row[c])));
  const sets = cols
    .filter((c) => c !== "id" && c !== parentCol && !keyCols.includes(c))
    .map((c) => `${c} = VALUES(${c})`);
  return (
    `INSERT INTO ${table} (${cols.join(", ")})\n` +
    `SELECT ${select.join(", ")} FROM ${parentTable} p WHERE p.slug = ${q(parentSlug)}\n` +
    `ON DUPLICATE KEY UPDATE ${sets.join(", ")};\n`
  );
}

const EXC = ["id", "locationId", "title", "slug", "description", "included", "excluded", "durationMinutes",
  "meetingPoint", "mapUrl", "whatToBring", "images", "priceAdult", "priceChild", "capacityDefault",
  "cutoffHoursBefore", "cutoffTime", "status", "pricingType", "cardImageUrl", "headerImageUrl", "minGuests"];
const DEP = ["id", "excursionId", "time", "daysOfWeek", "isActive"];
const RI = ["id", "locationId", "name", "slug", "description", "images", "priceAdult", "priceChild", "status",
  "durationMinutes", "cardImageUrl", "headerImageUrl"];
const SPOT = ["id", "rentalItemId", "code", "isActive", "quantity"];
const TS = ["id", "rentalItemId", "label", "startTime", "endTime", "isActive"];

const raw = (sql) => prisma.$queryRawUnsafe(sql);

async function main() {
  const excursions = await raw(`SELECT ${EXC.join(", ")} FROM excursions ORDER BY slug`);
  const rentals = await raw(`SELECT ${RI.join(", ")} FROM rental_items ORDER BY slug`);
  const deps = await raw(
    `SELECT d.${DEP.join(", d.")}, e.slug AS _slug FROM departure_times d
     JOIN excursions e ON e.id = d.excursionId ORDER BY e.slug, d.time`
  );
  const spots = await raw(
    `SELECT s.${SPOT.join(", s.")}, r.slug AS _slug FROM rental_spots s
     JOIN rental_items r ON r.id = s.rentalItemId ORDER BY r.slug, s.code`
  );
  const slots = await raw(
    `SELECT t.${TS.join(", t.")}, r.slug AS _slug FROM rental_time_slots t
     JOIN rental_items r ON r.id = t.rentalItemId ORDER BY r.slug, t.startTime`
  );

  // Image paths live on disk, not in the database, so they get listed for
  // copying rather than silently assumed to exist on the host.
  const media = new Set();
  for (const r of [...excursions, ...rentals]) {
    for (const k of ["cardImageUrl", "headerImageUrl"]) if (r[k]) media.add(r[k]);
    let imgs = r.images;
    if (typeof imgs === "string") {
      try { imgs = JSON.parse(imgs); } catch { imgs = null; }
    }
    if (Array.isArray(imgs)) for (const i of imgs) if (i) media.add(i);
  }

  const L = [];
  L.push(`-- Bring the hosted catalogue in line with local.`);
  L.push(`--`);
  L.push(`-- GENERATED by prisma/generate-catalogue-sync.js on ${new Date().toISOString().slice(0, 10)}.`);
  L.push(`-- Don't hand-edit this file — change the local database and re-run the`);
  L.push(`-- generator, so local stays the single source of truth.`);
  L.push(`--`);
  L.push(`--   mysql -u USER -p --default-character-set=utf8mb4 DBNAME < sync-catalogue-to-live.sql`);
  L.push(`--`);
  L.push(`-- The --default-character-set=utf8mb4 is required, or the accented`);
  L.push(`-- characters in the descriptions are mangled on import.`);
  L.push(`--`);
  L.push(`-- Rows are matched on each table's own unique key (excursions.slug,`);
  L.push(`-- rental_items.slug, rental_spots(item, code), rental_time_slots(item, label))`);
  L.push(`-- and never on id, so a row that already exists on the host is updated in`);
  L.push(`-- place and keeps the id its existing bookings point at. The location is`);
  L.push(`-- resolved at run time, because the hosted location id differs from local.`);
  L.push(`--`);
  L.push(`-- Nothing here deletes a catalogue item: one that exists on the host but`);
  L.push(`-- not locally is left in place rather than dropped, because it may have`);
  L.push(`-- bookings against it. Retire those from the admin panel instead.`);
  L.push(`--`);
  L.push(`-- Departure times are the one exception — they are replaced per excursion,`);
  L.push(`-- which is safe because bookings reference the excursion, not the`);
  L.push(`-- departure_times row. Rental spots and time slots that exist on the host`);
  L.push(`-- but not locally are deactivated rather than deleted, so they stop being`);
  L.push(`-- bookable without breaking the bookings already attached to them.`);
  L.push(`--`);
  L.push(`-- Bookings, orders, locations, settings and admin users are untouched.`);
  L.push(``);
  L.push(`SET NAMES utf8mb4;`);
  L.push(``);
  L.push(`START TRANSACTION;`);
  L.push(``);
  L.push(`-- The host's location row (local 'coccolobo-main' vs live 'carambola-main'),`);
  L.push(`-- resolved by age rather than by a hardcoded id.`);
  L.push(`SET @loc = (SELECT id FROM locations ORDER BY createdAt LIMIT 1);`);
  L.push(``);
  L.push(`-- ===================== Excursions =====================`);

  for (const e of excursions) {
    L.push(``);
    L.push(`-- ${e.title}`);
    L.push(upsert("excursions", EXC, { ...e, locationId: rawExpr("@loc") }, ["slug"]).trimEnd());
    L.push(`DELETE FROM departure_times WHERE excursionId = (SELECT id FROM excursions WHERE slug = ${q(e.slug)});`);
    for (const d of deps.filter((x) => x._slug === e.slug)) {
      const sel = DEP.map((c) => (c === "excursionId" ? "p.id" : q(d[c])));
      L.push(
        `INSERT INTO departure_times (${DEP.join(", ")})\n` +
        `SELECT ${sel.join(", ")} FROM excursions p WHERE p.slug = ${q(e.slug)};`
      );
    }
  }

  L.push(``);
  L.push(`-- ===================== Rental items =====================`);
  for (const r of rentals) {
    L.push(``);
    L.push(`-- ${r.name}`);
    L.push(upsert("rental_items", RI, { ...r, locationId: rawExpr("@loc") }, ["slug"]).trimEnd());
    const mySpots = spots.filter((x) => x._slug === r.slug);
    const mySlots = slots.filter((x) => x._slug === r.slug);
    for (const s of mySpots) {
      L.push(upsertChild("rental_spots", SPOT, s, "rentalItemId", "rental_items", r.slug, ["code"]).trimEnd());
    }
    for (const t of mySlots) {
      L.push(upsertChild("rental_time_slots", TS, t, "rentalItemId", "rental_items", r.slug, ["label"]).trimEnd());
    }
    // Rows the host has but local doesn't are extra bookable inventory, so
    // parity means retiring them. They are deactivated rather than deleted,
    // because an existing booking may point at one.
    const parent = `(SELECT id FROM rental_items WHERE slug = ${q(r.slug)})`;
    if (mySpots.length) {
      L.push(
        `UPDATE rental_spots SET isActive = 0 WHERE rentalItemId = ${parent}\n` +
        `  AND code NOT IN (${mySpots.map((s) => q(s.code)).join(", ")});`
      );
    }
    if (mySlots.length) {
      L.push(
        `UPDATE rental_time_slots SET isActive = 0 WHERE rentalItemId = ${parent}\n` +
        `  AND label NOT IN (${mySlots.map((t) => q(t.label)).join(", ")});`
      );
    }
  }

  L.push(``);
  L.push(`COMMIT;`);
  L.push(``);
  L.push(`-- ===================== Verify =====================`);
  L.push(`SELECT slug, title, durationMinutes, cutoffTime, minGuests, pricingType, status FROM excursions ORDER BY slug;`);
  L.push(`SELECT slug, name, durationMinutes, priceAdult, status FROM rental_items ORDER BY slug;`);
  L.push(`SELECT 'leftover WiFi / persons / Cocolobo' AS check_name,`);
  L.push(`  (SELECT COUNT(*) FROM excursions WHERE CONCAT_WS(' ', description, included, excluded) REGEXP 'WiFi|persons|Cocolobo Beach')`);
  L.push(`  + (SELECT COUNT(*) FROM rental_items WHERE description REGEXP 'WiFi|persons|Cocolobo Beach') AS should_be_zero;`);
  L.push(``);
  L.push(`-- ===================== Image files =====================`);
  L.push(`-- These rows reference the files below. Images are stored on disk, not in`);
  L.push(`-- the database, so copy them to the same paths under the host's uploads`);
  L.push(`-- folder — otherwise the pages will render broken images.`);
  const list = [...media].sort();
  for (const m of list) L.push(`--   ${m}`);
  if (list.length === 0) L.push(`--   (none)`);
  L.push(``);

  const out = path.join(__dirname, "sync-catalogue-to-live.sql");
  fs.writeFileSync(out, L.join("\n"), "utf8");
  console.log(`wrote ${out}`);
  console.log(
    `excursions=${excursions.length} departureTimes=${deps.length} rentalItems=${rentals.length} ` +
    `spots=${spots.length} timeSlots=${slots.length} mediaFiles=${media.size}`
  );
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
