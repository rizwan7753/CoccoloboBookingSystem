/** Turns a title/name into a URL-friendly slug — lowercase, alphanumeric
 *  words joined by single hyphens, accents stripped. */
export function slugify(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
